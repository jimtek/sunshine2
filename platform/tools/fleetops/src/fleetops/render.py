"""Render Kueue manifests and simulated KWOK nodes from config/platform.yaml.

The rendered files are committed so reviewers see the real objects in pull
requests; `fleetops render --check` fails CI if they drift from the config.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml

from . import platform as pf

KUEUE_API = "kueue.x-k8s.io/v1beta1"
POOL_LABEL = "platform.gpu/pool"
TEAM_LABEL = "platform.gpu/team"
HEADER = "# GENERATED by `fleetops render` from config/platform.yaml. Do not edit.\n"


def _qty(resource: str, value: int) -> Any:
    return f"{value}Gi" if resource == "memory" else value


def resource_flavors(cfg: dict) -> list[dict]:
    docs = []
    for name, pool in cfg["pools"].items():
        docs.append({
            "apiVersion": KUEUE_API, "kind": "ResourceFlavor",
            "metadata": {"name": name, "labels": {"platform.gpu/instance-type": pool["instance_type"]}},
            "spec": {
                "nodeLabels": {POOL_LABEL: name},
                "tolerations": [
                    {"key": POOL_LABEL, "operator": "Equal", "value": name, "effect": "NoSchedule"},
                    {"key": "nvidia.com/gpu", "operator": "Exists", "effect": "NoSchedule"},
                ],
            },
        })
    return docs


def _flavor_order(cfg: dict) -> list[str]:
    # Capacity Blocks first: they expire on a fixed clock, so use them before
    # longer-term reservations. Dev last; jobs reach it via nodeSelector.
    pools = list(cfg["pools"])
    ranked = [p for p in pools if "ends_at" in cfg["pools"][p]]
    ranked += [p for p in pools if p not in ranked and "max_runtime" not in cfg["pools"][p]]
    ranked += [p for p in pools if p not in ranked]
    return ranked


def cluster_queues(cfg: dict) -> list[dict]:
    quotas = pf.team_quotas(cfg)
    preemptible = cfg["priorities"].get("preemptible", {}).get("value", 0)
    docs = []
    for team in cfg["teams"]:
        flavors = []
        for pool in _flavor_order(cfg):
            flavors.append({
                "name": pool,
                "resources": [
                    {"name": r, "nominalQuota": _qty(r, quotas[team][pool][r])} for r in pf.RESOURCES
                ],
            })
        docs.append({
            "apiVersion": KUEUE_API, "kind": "ClusterQueue",
            "metadata": {"name": team},
            "spec": {
                "cohort": cfg["cohort"],
                "namespaceSelector": {"matchLabels": {TEAM_LABEL: team}},
                "queueingStrategy": "BestEffortFIFO",
                "flavorFungibility": {"whenCanBorrow": "TryNextFlavor", "whenCanPreempt": "TryNextFlavor"},
                "preemption": {
                    # Take back lent quota from other teams, and let higher
                    # priority work displace this team's own lower priority work.
                    "reclaimWithinCohort": "Any",
                    "withinClusterQueue": "LowerPriority",
                    # When borrowing, only preemptible backfill may be displaced.
                    "borrowWithinCohort": {"policy": "LowerPriority", "maxPriorityThreshold": preemptible},
                },
                "resourceGroups": [{"coveredResources": list(pf.RESOURCES), "flavors": flavors}],
            },
        })
    return docs


def namespaces_and_queues(cfg: dict) -> list[dict]:
    docs = []
    for team in cfg["teams"]:
        docs.append({
            "apiVersion": "v1", "kind": "Namespace",
            "metadata": {"name": team, "labels": {TEAM_LABEL: team, "team": team, "platform.gpu/research": "true"}},
        })
        docs.append({
            "apiVersion": KUEUE_API, "kind": "LocalQueue",
            "metadata": {"name": "default", "namespace": team},
            "spec": {"clusterQueue": team},
        })
    return docs


def priority_classes(cfg: dict) -> list[dict]:
    return [{
        "apiVersion": KUEUE_API, "kind": "WorkloadPriorityClass",
        "metadata": {"name": name}, "value": p["value"], "description": p["desc"],
    } for name, p in cfg["priorities"].items()]


def team_role_bindings(cfg: dict) -> list[dict]:
    """Bind each team's Kubernetes group (mapped from its IAM role by EKS
    access entries) to the gpu-researcher role in its own namespace only."""
    return [{
        "apiVersion": "rbac.authorization.k8s.io/v1", "kind": "RoleBinding",
        "metadata": {"name": "gpu-researchers", "namespace": team},
        "roleRef": {"apiGroup": "rbac.authorization.k8s.io", "kind": "ClusterRole", "name": "gpu-researcher"},
        "subjects": [{"apiGroup": "rbac.authorization.k8s.io", "kind": "Group", "name": team}],
    } for team in cfg["teams"]]


def kwok_nodes(cfg: dict, zone: str = "sim-a") -> list[dict]:
    docs = []
    for pname, pool in cfg["pools"].items():
        res = {
            "cpu": str(pool["cpu_per_node"]),
            "memory": pool["memory_per_node"],
            "pods": "110",
            "nvidia.com/gpu": str(pool["gpus_per_node"]),
            "vpc.amazonaws.com/efa": str(pool["efa_per_node"]),
        }
        for i in range(pool["nodes"]):
            docs.append({
                "apiVersion": "v1", "kind": "Node",
                "metadata": {
                    "name": f"kwok-{pname}-{i:02d}",
                    "annotations": {"kwok.x-k8s.io/node": "fake", "node.alpha.kubernetes.io/ttl": "0"},
                    "labels": {
                        "type": "kwok",
                        "kubernetes.io/role": "agent",
                        "kubernetes.io/hostname": f"kwok-{pname}-{i:02d}",
                        "node.kubernetes.io/instance-type": pool["instance_type"],
                        "topology.kubernetes.io/zone": zone,
                        POOL_LABEL: pname,
                        "nvidia.com/gpu.present": "true",
                    },
                },
                "spec": {"taints": [
                    {"key": POOL_LABEL, "value": pname, "effect": "NoSchedule"},
                    {"key": "nvidia.com/gpu", "value": "present", "effect": "NoSchedule"},
                ]},
                "status": {"allocatable": res, "capacity": res},
            })
    return docs


def _dump(docs: list[dict]) -> str:
    return HEADER + "---\n".join(yaml.safe_dump(d, sort_keys=False) for d in docs)


def outputs(cfg: dict) -> dict[str, str]:
    """Relative path (from platform/) -> file content."""
    return {
        "cluster/kueue/resource-flavors.yaml": _dump(resource_flavors(cfg)),
        "cluster/kueue/cluster-queues.yaml": _dump(cluster_queues(cfg)),
        "cluster/kueue/team-namespaces.yaml": _dump(namespaces_and_queues(cfg)),
        "cluster/kueue/priorities.yaml": _dump(priority_classes(cfg)),
        "cluster/rbac/team-bindings.yaml": _dump(team_role_bindings(cfg)),
        "sim/kwok-nodes.yaml": _dump(kwok_nodes(cfg)),
    }


def write(cfg: dict, root: Path) -> list[str]:
    written = []
    for rel, content in outputs(cfg).items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        written.append(rel)
    return written


def drift(cfg: dict, root: Path) -> list[str]:
    return [rel for rel, content in outputs(cfg).items()
            if not (root / rel).exists() or (root / rel).read_text() != content]
